function catalog = case_catalog()
%CASE_CATALOG Official MATPOWER 8.1 case sources used in the benchmark.
%
% The 9-bus case is the standard WSCC/3-machine 9-bus benchmark and the
% 39-bus case is the New England system. The 14-, 30-, 57-, and 118-bus
% cases are IEEE test systems.

base = 'https://raw.githubusercontent.com/MATPOWER/matpower/8.1/data/';

% List the local case keys, MATLAB function names, display names, and
% official source URLs.  The local copies are used during the run.
catalog = struct( ...
    'key', {'case9','case14','case_ieee30','case39','case57','case118'}, ...
    'functionName', {'case9','case14','case_ieee30','case39','case57','case118'}, ...
    'displayName', {'9-bus WSCC','IEEE 14-bus','IEEE 30-bus', ...
                    'New England 39-bus','IEEE 57-bus','IEEE 118-bus'}, ...
    'shortName', {'9-bus','14-bus','30-bus','39-bus','57-bus','118-bus'}, ...
    'url', { ...
        [base,'case9.m'], ...
        [base,'case14.m'], ...
        [base,'case_ieee30.m'], ...
        [base,'case39.m'], ...
        [base,'case57.m'], ...
        [base,'case118.m']});
end
