function rows = verify_certified_points(data,network,c,cfg)
%VERIFY_CERTIFIED_POINTS Check the two theorem bounds and added intervals.
baseline = [c.lambdaB2,c.lambdaBInf];
proposed = [c.lambdaT2,c.lambdaTInf];
gamma = acos(([c.chi2,c.chiInf]-1)./([c.chi2,c.chiInf]+1));
normOrders = [2,inf];
normNames = ["2","infinity"];
rows = cell(4,1);
for j = 1:2
    targets = [0.5*(baseline(j)+proposed(j)),0.999*proposed(j)];
    for k = 1:2
        lambda = targets(k);
        [theta,solver] = normbench.continue_equilibrium(network, ...
            data.varpiNominal,data.referenceBus,0,zeros(data.N,1),lambda,cfg,50);
        assert(solver.converged,'%s: certified equilibrium solve failed.',data.key);
        metrics = normbench.equilibrium_metrics(data,network,lambda,theta);
        angleNorm = norm(metrics.edgeAngle,normOrders(j));
        assert(metrics.powerFlowResidual < 1e-8 && angleNorm < gamma(j), ...
            '%s: the claimed theorem angle bound did not pass.',data.key);
        assert(metrics.minimumYLL > 0 && metrics.numberOfNearZeroModes == 1 ...
            && metrics.maximumRealPart < 0, ...
            '%s: a certified equilibrium failed the local stability check.',data.key);
        if k == 1
            assert(lambda > baseline(j) && lambda < proposed(j), ...
                '%s: no strictly added same-norm interval.',data.key);
            point = "added-interval midpoint";
        else
            point = "0.999 proposed limit";
        end
        row = struct('System',string(data.displayName),'Norm',normNames(j), ...
            'Point',point,'LoadingFactor',lambda, ...
            'ExistingLhsOverRhs',lambda/baseline(j), ...
            'ProposedLhsOverRhs',lambda/proposed(j), ...
            'PowerFlowResidual',metrics.powerFlowResidual, ...
            'EdgeAngleNorm',angleNorm,'TheoremAngleBound',gamma(j), ...
            'MaximumEdgeAngleRad',metrics.maximumEdgeAngle, ...
            'MinimumLllEigenvalue',metrics.minimumYLL, ...
            'NearZeroModes',metrics.numberOfNearZeroModes, ...
            'MaximumNonzeroRealPart',metrics.maximumRealPart);
        rows{2*(j-1)+k} = row;
    end
end
rows = vertcat(rows{:});
end
