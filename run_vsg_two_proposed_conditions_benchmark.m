%% 2. Determine B and A from Y, then calculate the four norm-based limits.
loadingLimits = zeros(6,4); % Column order in Table II: lambda_1, lambda_3, lambda_2, lambda_4.
g = @(x) sqrt(x)-(x-1).*atan(1./sqrt(x)); % Radius function in the four conditions.

for k = 1:6
    parallel = [];
    switch k % Select the directly assigned matrices.
        case 1
            Y = Y9;   V = V9;   varpi = varpi9;
        case 2
            Y = Y14;  V = V14;  varpi = varpi14;
        case 3
            Y = Y30;  V = V30;  varpi = varpi30;
        case 4
            Y = Y39;  V = V39;  varpi = varpi39;
        case 5
            Y = Y57;  V = V57;  varpi = varpi57;  parallel = parallel57;
        case 6
            Y = Y118; V = V118; varpi = varpi118; parallel = parallel118;
    end
    N = size(Y,1);
    [from,to,b] = find(triu(imag(Y),1)); % Each upper-triangular entry gives a connection.

    % Keep parallel lines separate: merging them would change the branch-space norms.
    for p = 1:size(parallel,1)
        e = find(from==parallel(p,1) & to==parallel(p,2));
        from(end+1,1) = from(e);
        to(end+1,1) = to(e);
        b(e) = parallel(p,3);        % First parallel line.
        b(end+1,1) = parallel(p,4); % Second parallel line.
    end

    E = numel(b);
    B = zeros(N,E); % One +1 and one -1 in each incidence-matrix column.
    for e = 1:E
        B(from(e),e) = 1;
        B(to(e),e) = -1;
    end
    A = diag(V(from).*V(to).*b); % Line weight: voltage_i * voltage_j * susceptance.
    L = B*A*B.';                % Weighted graph Laplacian.

    % Remove the original AC-loss surplus so the lossless injections sum to zero.
    source = varpi>0;
    varpi(source) = varpi(source)*(-sum(varpi(~source))/sum(varpi(source)));

    Ldagger = pinv(L);        % Moore-Penrose inverse of L.
    P = B.'*Ldagger*B*A;      % Cut-space projection.
    u = B.'*Ldagger*varpi;    % Branch loading vector at lambda = 1.
    p2 = norm(P,2);
    pInf = norm(P,inf);
    u2 = norm(u,2);
    uInf = norm(u,inf);

    loadingLimits(k,1) = g(p2)/u2;                       % Existing 2-norm condition.
    loadingLimits(k,2) = g(sqrt((2*p2^2+1)/3))/u2;        % Proposed 2-norm condition.
    loadingLimits(k,3) = g(pInf)/uInf;                   % Existing infinity-norm condition.
    loadingLimits(k,4) = g((2*pInf+1)/3)/uInf;            % Proposed infinity-norm condition.
end

%% 3. Print Table II; no files are exported.
resultsTable = array2table(loadingLimits, ...
    'VariableNames',{'lambda_1','lambda_3','lambda_2','lambda_4'});
resultsTable = addvars(resultsTable,string(systemNames.'), ...
    'Before',1,'NewVariableNames','System');

fprintf('\nCritical loading factors\n');
fprintf('%-10s %12s %12s %12s %12s\n', ...
    'System','lambda_1','lambda_3','lambda_2','lambda_4');
for k = 1:6
    fprintf('%-10s %12.4f %12.4f %12.4f %12.4f\n',systemNames{k},loadingLimits(k,:));
end
